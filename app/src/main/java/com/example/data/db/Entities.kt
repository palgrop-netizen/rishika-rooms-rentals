package com.example.data.db

import androidx.room.Entity
import androidx.room.ForeignKey
import androidx.room.Index
import androidx.room.PrimaryKey

@Entity(tableName = "rooms")
data class RoomEntity(
    @PrimaryKey val roomNumber: Int,
    val roomLabel: String = "Room $roomNumber",
    val currentTenantId: Long? = null,
    val lastMeterReading: Double = 0.0
)

@Entity(
    tableName = "tenants",
    indices = [Index("currentRoomNumber"), Index("isActive")]
)
data class TenantEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0L,
    val name: String,
    val mobileNumber: String,
    val currentRoomNumber: Int,
    val monthlyRentPaise: Long,
    val entryDate: String, // yyyy-MM-dd
    val kycType: String,
    val kycNumber: String,
    val kycDocumentPath: String? = null,
    val kycDocumentName: String? = null,
    val notes: String = "",
    val advanceBalancePaise: Long = 0L,
    val isActive: Boolean = true,
    val vacatedDate: String? = null,
    val createdAt: Long = System.currentTimeMillis()
)

@Entity(
    tableName = "rent_entries",
    foreignKeys = [
        ForeignKey(
            entity = TenantEntity::class,
            parentColumns = ["id"],
            childColumns = ["tenantId"],
            onDelete = ForeignKey.CASCADE
        )
    ],
    indices = [
        Index(value = ["tenantId", "cycleIndex"], unique = true),
        Index("tenantId"),
        Index("roomNumber"),
        Index("dueDate")
    ]
)
data class RentEntryEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0L,
    val tenantId: Long,
    val roomNumber: Int,
    val cycleIndex: Int,
    val rentMonth: String, // yyyy-MM
    val dueDate: String, // yyyy-MM-dd
    val rentAmountPaise: Long,
    val advanceAppliedPaise: Long = 0L,
    val amountPaidPaise: Long = 0L,
    val writeOffPaise: Long = 0L,
    val pendingPaise: Long = rentAmountPaise,
    val status: String = "PENDING", // PENDING, PARTIAL, PAID, WRITTEN_OFF
    val isAutoGenerated: Boolean = true,
    val createdAt: Long = System.currentTimeMillis()
)

@Entity(
    tableName = "suppressed_rent_cycles",
    primaryKeys = ["tenantId", "cycleIndex"],
    foreignKeys = [
        ForeignKey(
            entity = TenantEntity::class,
            parentColumns = ["id"],
            childColumns = ["tenantId"],
            onDelete = ForeignKey.CASCADE
        )
    ]
)
data class SuppressedRentCycleEntity(
    val tenantId: Long,
    val cycleIndex: Int,
    val rentMonth: String,
    val deletedAt: Long = System.currentTimeMillis()
)

@Entity(
    tableName = "electricity_bills",
    foreignKeys = [
        ForeignKey(
            entity = TenantEntity::class,
            parentColumns = ["id"],
            childColumns = ["tenantId"],
            onDelete = ForeignKey.CASCADE
        )
    ],
    indices = [Index("tenantId"), Index("roomNumber"), Index("periodFrom")]
)
data class ElectricityBillEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0L,
    val roomNumber: Int,
    val tenantId: Long,
    val periodFrom: String, // yyyy-MM-dd
    val periodTo: String, // yyyy-MM-dd
    val previousReading: Double,
    val currentReading: Double,
    val unitsConsumed: Double,
    val ratePerUnitPaise: Long,
    val totalBillPaise: Long,
    val amountPaidPaise: Long = 0L,
    val pendingPaise: Long = totalBillPaise,
    val status: String = "PENDING", // PENDING, PARTIAL, PAID
    val createdAt: Long = System.currentTimeMillis()
)

@Entity(
    tableName = "payment_receipts",
    foreignKeys = [
        ForeignKey(
            entity = TenantEntity::class,
            parentColumns = ["id"],
            childColumns = ["tenantId"],
            onDelete = ForeignKey.CASCADE
        )
    ],
    indices = [
        Index(value = ["receiptNumber"], unique = true),
        Index("tenantId"),
        Index("paymentDate")
    ]
)
data class PaymentReceiptEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0L,
    val receiptNumber: String,
    val tenantId: Long,
    val roomNumber: Int,
    val paymentDate: String, // yyyy-MM-dd
    val totalAmountPaise: Long,
    val paymentMode: String, // Cash, UPI, Bank Transfer, Other
    val remarks: String = "",
    val rentAdjustedPaise: Long = 0L,
    val electricityAdjustedPaise: Long = 0L,
    val advanceAddedPaise: Long = 0L,
    val createdAt: Long = System.currentTimeMillis()
)

@Entity(
    tableName = "payment_allocations",
    foreignKeys = [
        ForeignKey(
            entity = PaymentReceiptEntity::class,
            parentColumns = ["id"],
            childColumns = ["paymentId"],
            onDelete = ForeignKey.CASCADE
        ),
        ForeignKey(
            entity = TenantEntity::class,
            parentColumns = ["id"],
            childColumns = ["tenantId"],
            onDelete = ForeignKey.CASCADE
        )
    ],
    indices = [Index("paymentId"), Index("tenantId"), Index("targetType", "targetId")]
)
data class PaymentAllocationEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0L,
    val paymentId: Long,
    val tenantId: Long,
    val targetType: String, // RENT, ELECTRICITY, ADVANCE
    val targetId: Long? = null,
    val amountPaise: Long
)

@Entity(
    tableName = "advance_transactions",
    foreignKeys = [
        ForeignKey(
            entity = TenantEntity::class,
            parentColumns = ["id"],
            childColumns = ["tenantId"],
            onDelete = ForeignKey.CASCADE
        )
    ],
    indices = [Index("tenantId"), Index("paymentId"), Index("rentEntryId")]
)
data class AdvanceTransactionEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0L,
    val tenantId: Long,
    val type: String, // ADDED_FROM_PAYMENT, ADJUSTED_TO_RENT
    val amountPaise: Long,
    val paymentId: Long? = null,
    val rentEntryId: Long? = null,
    val transactionDate: String, // yyyy-MM-dd
    val remarks: String = "",
    val createdAt: Long = System.currentTimeMillis()
)

@Entity(
    tableName = "write_offs",
    foreignKeys = [
        ForeignKey(
            entity = TenantEntity::class,
            parentColumns = ["id"],
            childColumns = ["tenantId"],
            onDelete = ForeignKey.CASCADE
        ),
        ForeignKey(
            entity = RentEntryEntity::class,
            parentColumns = ["id"],
            childColumns = ["rentEntryId"],
            onDelete = ForeignKey.CASCADE
        )
    ],
    indices = [Index("tenantId"), Index("rentEntryId")]
)
data class WriteOffEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0L,
    val tenantId: Long,
    val rentEntryId: Long,
    val amountPaise: Long,
    val writeOffDate: String, // yyyy-MM-dd
    val remarks: String = "",
    val isReversed: Boolean = false,
    val reversedDate: String? = null,
    val createdAt: Long = System.currentTimeMillis()
)

@Entity(
    tableName = "follow_ups",
    foreignKeys = [
        ForeignKey(
            entity = TenantEntity::class,
            parentColumns = ["id"],
            childColumns = ["tenantId"],
            onDelete = ForeignKey.CASCADE
        )
    ],
    indices = [Index("tenantId"), Index("status"), Index("promisedPaymentDate")]
)
data class FollowUpEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0L,
    val tenantId: Long,
    val roomNumber: Int,
    val followUpDate: String, // yyyy-MM-dd
    val promisedPaymentDate: String, // yyyy-MM-dd
    val pendingAmountPaise: Long,
    val remarks: String = "",
    val status: String = "PENDING", // PENDING, COMPLETED
    val completedDate: String? = null,
    val createdAt: Long = System.currentTimeMillis()
)

@Entity(
    tableName = "room_transfers",
    foreignKeys = [
        ForeignKey(
            entity = TenantEntity::class,
            parentColumns = ["id"],
            childColumns = ["tenantId"],
            onDelete = ForeignKey.CASCADE
        )
    ],
    indices = [Index("tenantId"), Index("fromRoomNumber"), Index("toRoomNumber")]
)
data class RoomTransferEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0L,
    val tenantId: Long,
    val fromRoomNumber: Int,
    val toRoomNumber: Int,
    val transferDate: String, // yyyy-MM-dd
    val remarks: String = "",
    val createdAt: Long = System.currentTimeMillis()
)

@Entity(tableName = "app_settings")
data class AppSettingsEntity(
    @PrimaryKey val id: Int = 1,
    val defaultElectricityRatePaise: Long = 800L, // Rs. 8.00 / unit
    val nextReceiptSeq: Int = 1,
    val lastBackupEpochMs: Long = 0L,
    val backupReminderDays: Int = 7
)
