package com.example.data.db

import org.json.JSONArray
import org.json.JSONObject

data class BackupPayload(
    val backupVersion: Int,
    val exportedAtEpochMs: Long,
    val exportedAtIso: String,
    val appSettings: AppSettingsEntity,
    val rooms: List<RoomEntity>,
    val tenants: List<TenantEntity>,
    val rentEntries: List<RentEntryEntity>,
    val suppressedRentCycles: List<SuppressedRentCycleEntity>,
    val electricityBills: List<ElectricityBillEntity>,
    val paymentReceipts: List<PaymentReceiptEntity>,
    val paymentAllocations: List<PaymentAllocationEntity>,
    val advanceTransactions: List<AdvanceTransactionEntity>,
    val writeOffs: List<WriteOffEntity>,
    val followUps: List<FollowUpEntity>,
    val roomTransfers: List<RoomTransferEntity>
)

