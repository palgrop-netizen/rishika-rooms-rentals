                })
            }
        })

        root.put("tenants", JSONArray().apply {
            payload.tenants.forEach { t ->
                put(JSONObject().apply {
                    put("id", t.id)
                    put("name", t.name)
                    put("mobileNumber", t.mobileNumber)
                    put("currentRoomNumber", t.currentRoomNumber)
                    put("monthlyRentPaise", t.monthlyRentPaise)
                    put("entryDate", t.entryDate)
                    put("kycType", t.kycType)
                    put("kycNumber", t.kycNumber)
                    put("kycDocumentPath", t.kycDocumentPath ?: JSONObject.NULL)
                    put("kycDocumentName", t.kycDocumentName ?: JSONObject.NULL)
                    put("notes", t.notes)
                    put("advanceBalancePaise", t.advanceBalancePaise)
                    put("isActive", t.isActive)
                    put("vacatedDate", t.vacatedDate ?: JSONObject.NULL)
                    put("createdAt", t.createdAt)
                })
            }
        })

        root.put("rentEntries", JSONArray().apply {
            payload.rentEntries.forEach { re ->
                put(JSONObject().apply {
                    put("id", re.id)
                    put("tenantId", re.tenantId)
                    put("roomNumber", re.roomNumber)
                    put("cycleIndex", re.cycleIndex)
                    put("rentMonth", re.rentMonth)
                    put("dueDate", re.dueDate)
                    put("rentAmountPaise", re.rentAmountPaise)
                    put("advanceAppliedPaise", re.advanceAppliedPaise)
                    put("amountPaidPaise", re.amountPaidPaise)
                    put("writeOffPaise", re.writeOffPaise)
                    put("pendingPaise", re.pendingPaise)
                    put("status", re.status)
                    put("isAutoGenerated", re.isAutoGenerated)
                    put("createdAt", re.createdAt)
                })
            }
        })

        root.put("suppressedRentCycles", JSONArray().apply {
            payload.suppressedRentCycles.forEach { sc ->
                put(JSONObject().apply {
                    put("tenantId", sc.tenantId)
                    put("cycleIndex", sc.cycleIndex)
                    put("rentMonth", sc.rentMonth)
                    put("deletedAt", sc.deletedAt)
                })
            }
        })

        root.put("electricityBills", JSONArray().apply {
