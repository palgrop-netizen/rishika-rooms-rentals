        root.put("app", "Rishika Rooms & Rentals")
        root.put("brand", "RRR")
        root.put("backupVersion", payload.backupVersion)
        root.put("exportedAtEpochMs", payload.exportedAtEpochMs)
        root.put("exportedAtIso", payload.exportedAtIso)

        root.put("appSettings", JSONObject().apply {
            put("id", payload.appSettings.id)
            put("defaultElectricityRatePaise", payload.appSettings.defaultElectricityRatePaise)
            put("nextReceiptSeq", payload.appSettings.nextReceiptSeq)
            put("lastBackupEpochMs", payload.appSettings.lastBackupEpochMs)
            put("backupReminderDays", payload.appSettings.backupReminderDays)
        })

        root.put("rooms", JSONArray().apply {
            payload.rooms.forEach { r ->
                put(JSONObject().apply {
                    put("roomNumber", r.roomNumber)
                    put("roomLabel", r.roomLabel)
                    put("currentTenantId", r.currentTenantId ?: JSONObject.NULL)
