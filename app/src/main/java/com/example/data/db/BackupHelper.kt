                    put("remarks", rt.remarks)
                    put("createdAt", rt.createdAt)
                })
            }
        })

        return root.toString(2)
    }

    fun parseAndValidate(jsonString: String): Result<BackupPayload> {
        return try {
            val root = JSONObject(jsonString)
            val appName = root.optString("app", "")
            val version = root.optInt("backupVersion", -1)
            if (appName != "Rishika Rooms & Rentals" || version != CURRENT_BACKUP_VERSION) {
                return Result.failure(
                    IllegalArgumentException("Unsupported or invalid RRR backup file (version=$version).")
                )
            }

            val requiredArrays = listOf(
                "rooms", "tenants", "rentEntries", "electricityBills",
                "paymentReceipts", "paymentAllocations", "advanceTransactions",
                "writeOffs", "followUps", "roomTransfers"
            )
            for (key in requiredArrays) {
                if (!root.has(key) || root.optJSONArray(key) == null) {
                    return Result.failure(IllegalArgumentException("Backup missing required section: $key"))
                }
            }

            val settingsObj = root.optJSONObject("appSettings")
            val settings = if (settingsObj != null) {
                AppSettingsEntity(
                    id = 1,
                    defaultElectricityRatePaise = settingsObj.optLong("defaultElectricityRatePaise", 800L),
                    nextReceiptSeq = settingsObj.optInt("nextReceiptSeq", 1).coerceAtLeast(1),
                    lastBackupEpochMs = settingsObj.optLong("lastBackupEpochMs", 0L),
                    backupReminderDays = settingsObj.optInt("backupReminderDays", 7).coerceAtLeast(1)
                )
            } else {
                AppSettingsEntity()
            }

            val rooms = parseRooms(root.getJSONArray("rooms"))
            val tenants = parseTenants(root.getJSONArray("tenants"))
            val tenantIds = tenants.map { it.id }.toSet()
            if (tenantIds.size != tenants.size) {
                return Result.failure(IllegalArgumentException("Duplicate tenant IDs detected in backup."))
            }

            val rentEntries = parseRentEntries(root.getJSONArray("rentEntries"))
            val rentIds = rentEntries.map { it.id }.toSet()
            if (rentIds.size != rentEntries.size) {
                return Result.failure(IllegalArgumentException("Duplicate rent entry IDs detected in backup."))
            }
            if (rentEntries.any { it.tenantId !in tenantIds }) {
                return Result.failure(IllegalArgumentException("Backup contains rent entries referencing missing tenants."))
            }

            val suppressed = if (root.has("suppressedRentCycles") && root.optJSONArray("suppressedRentCycles") != null) {
                parseSuppressed(root.getJSONArray("suppressedRentCycles")).filter { it.tenantId in tenantIds }
            } else {
                emptyList()
            }

            val bills = parseBills(root.getJSONArray("electricityBills"))
            if (bills.any { it.tenantId !in tenantIds }) {
                return Result.failure(IllegalArgumentException("Backup contains electricity bills referencing missing tenants."))
            }

            val receipts = parseReceipts(root.getJSONArray("paymentReceipts"))
            val receiptIds = receipts.map { it.id }.toSet()
            val receiptNumbers = receipts.map { it.receiptNumber }.toSet()
            if (receiptIds.size != receipts.size || receiptNumbers.size != receipts.size) {
                return Result.failure(IllegalArgumentException("Duplicate receipt IDs or receipt numbers in backup."))
            }
            if (receipts.any { it.tenantId !in tenantIds }) {
                return Result.failure(IllegalArgumentException("Backup contains receipts referencing missing tenants."))
            }

            val allocations = parseAllocations(root.getJSONArray("paymentAllocations"))
            if (allocations.any { it.paymentId !in receiptIds || it.tenantId !in tenantIds }) {
                return Result.failure(IllegalArgumentException("Backup contains orphaned payment allocations."))
            }

            val advanceTxs = parseAdvanceTxs(root.getJSONArray("advanceTransactions"))
            if (advanceTxs.any { it.tenantId !in tenantIds }) {
                return Result.failure(IllegalArgumentException("Backup contains advance transactions referencing missing tenants."))
            }

            val writeOffs = parseWriteOffs(root.getJSONArray("writeOffs"))
            if (writeOffs.any { it.tenantId !in tenantIds || it.rentEntryId !in rentIds }) {
                return Result.failure(IllegalArgumentException("Backup contains write-offs referencing missing records."))
            }

            val followUps = parseFollowUps(root.getJSONArray("followUps"))
            if (followUps.any { it.tenantId !in tenantIds }) {
                return Result.failure(IllegalArgumentException("Backup contains follow-ups referencing missing tenants."))
            }

            val transfers = parseTransfers(root.getJSONArray("roomTransfers"))
            if (transfers.any { it.tenantId !in tenantIds }) {
                return Result.failure(IllegalArgumentException("Backup contains room transfers referencing missing tenants."))
            }

            // Ensure all 13 rooms exist and reference valid active tenants
            val roomMap = rooms.associateBy { it.roomNumber }
            val normalizedRooms = (1..AppDatabase.TOTAL_ROOMS).map { num ->
                val existing = roomMap[num]
                if (existing != null) {
                    val validTenant = if (existing.currentTenantId != null && existing.currentTenantId in tenantIds) {
                        existing.currentTenantId
                    } else null
                    existing.copy(currentTenantId = validTenant)
                } else {
                    RoomEntity(roomNumber = num, roomLabel = "Room $num")
                }
            }

            Result.success(
                BackupPayload(
                    backupVersion = version,
                    exportedAtEpochMs = root.optLong("exportedAtEpochMs", System.currentTimeMillis()),
                    exportedAtIso = root.optString("exportedAtIso", ""),
                    appSettings = settings,
                    rooms = normalizedRooms,
                    tenants = tenants,
                    rentEntries = rentEntries,
                    suppressedRentCycles = suppressed,
                    electricityBills = bills,
                    paymentReceipts = receipts,
                    paymentAllocations = allocations,
                    advanceTransactions = advanceTxs,
                    writeOffs = writeOffs,
                    followUps = followUps,
                    roomTransfers = transfers
                )
            )
        } catch (e: Exception) {
            Result.failure(IllegalArgumentException("Invalid backup JSON: ${e.message ?: "parse error"}"))
        }
    }

    private fun JSONObject.optNullableLong(key: String): Long? =
        if (!has(key) || isNull(key)) null else optLong(key)

    private fun JSONObject.optNullableString(key: String): String? =
        if (!has(key) || isNull(key)) null else optString(key)

    private fun parseRooms(arr: JSONArray): List<RoomEntity> = List(arr.length()) { i ->
        val o = arr.getJSONObject(i)
        val num = o.getInt("roomNumber")
        RoomEntity(
            roomNumber = num,
            roomLabel = o.optString("roomLabel", "Room $num"),
            currentTenantId = o.optNullableLong("currentTenantId"),
            lastMeterReading = o.optDouble("lastMeterReading", 0.0)
        )
    }

    private fun parseTenants(arr: JSONArray): List<TenantEntity> = List(arr.length()) { i ->
        val o = arr.getJSONObject(i)
        TenantEntity(
