            payload.paymentReceipts.forEach { pr ->
                put(JSONObject().apply {
                    put("id", pr.id)
                    put("receiptNumber", pr.receiptNumber)
                    put("tenantId", pr.tenantId)
                    put("roomNumber", pr.roomNumber)
                    put("paymentDate", pr.paymentDate)
